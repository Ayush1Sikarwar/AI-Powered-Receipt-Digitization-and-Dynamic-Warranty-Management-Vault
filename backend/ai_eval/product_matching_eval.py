def build_catalog(db) -> list[dict]:
    from app.models.product import (
        Manufacturer,
        Product,
        ProductAlias,
        Retailer,
        RetailerCatalogEntry,
    )

    mfrs: dict[str, object] = {}
    products: list[dict] = []
    for mfr_name, brand, name, cat, model, sku, alias in CATALOG:
        if mfr_name not in mfrs:
            from app.ai.product.normalization import make_name_key

            m = Manufacturer(name=mfr_name, name_key=make_name_key(mfr_name))
            db.add(m)
            mfrs[mfr_name] = m
        p = Product(
            manufacturer_id=mfrs[mfr_name].id,
            brand=brand,
            canonical_name=name,
            category=cat,
            model_number=model,
            sku=sku,
        )
        db.add(p)
        db.flush()
        if alias:
            db.add(ProductAlias(product_id=p.id, alias_text=alias, source="EVAL"))
        products.append(
            {
                "id": p.id,
                "name": name,
                "brand": brand,
                "category": cat,
                "model": model,
                "sku": sku,
                "alias": alias,
                "mfr": mfr_name,
            }
        )
    r = Retailer(name="MegaMart", name_key="megamart")
    db.add(r)
    db.flush()
    # Retailer catalog entries for the first product of each manufacturer.
    seen = set()
    for mfr_name, _brand, _name, _cat, model, _sku, _alias in CATALOG:
        if mfr_name in seen:
            continue
        seen.add(mfr_name)
        pid = next(x["id"] for x in products if x["mfr"] == mfr_name)
        db.add(
            RetailerCatalogEntry(
                retailer_id=r.id,
                product_id=pid,
                catalog_sku=f"MM-{model[:6].upper()}",
                catalog_model=model,
                source="EVAL",
            )
        )
    db.commit()
    return products


def main() -> None:
    _evaldb.ensure_database()
    SessionLocal = _evaldb.session_factory()
    db = SessionLocal()

    from app.ai.product.matching import ProductQuery, decide, generate_candidates
    from app.core.config import get_settings

    settings = get_settings()
    products = build_catalog(db)

    # --- build query set (ground truth known by construction) ------------
    queries: list[dict] = []
    for p in products:
        queries.append({"kind": "exact_model", "gt": p["id"], "q": ProductQuery(product_name=p["name"], model_number=p["model"])})
        queries.append({"kind": "exact_sku", "gt": p["id"], "q": ProductQuery(sku=p["sku"], description=p["name"])})
        queries.append({"kind": "name_only", "gt": p["id"], "q": ProductQuery(product_name=p["name"])})
        queries.append({"kind": "brand_model", "gt": p["id"], "q": ProductQuery(brand=p["brand"], model_number=p["model"], product_name=p["category"])})
        if p["alias"]:
            queries.append({"kind": "alias", "gt": p["id"], "q": ProductQuery(product_name=p["alias"], description="")})
        # Noisy receipt line: real products appear with extra tokens.
        noisy = f"{p['category']} {p['model']} 60K" if p["category"] else f"{p['name']} 60K"
        queries.append({"kind": "noisy", "gt": p["id"], "q": ProductQuery(product_name=noisy)})
    for name, sku, model in NEGATIVE_QUERIES:
        queries.append({"kind": "negative", "gt": None, "q": ProductQuery(product_name=name, sku=sku, model_number=model)})

    # --- run the real engine ------------------------------------------------
    results = []
    for q in queries:
        candidates, _notes = generate_candidates(db, q["q"])
        status, chosen = decide(candidates, settings.confidence_auto_accept, settings.confidence_user_review)
        top1 = candidates[0].product_id if candidates else None
        top3 = [c.product_id for c in candidates[:3]]
        results.append(
            {
                "kind": q["kind"],
                "gt": q["gt"],
                "status": status.value,
                "top1": top1,
                "top3": top3,
                "n_candidates": len(candidates),
                "chosen": chosen.product_id if chosen else None,
                "method": candidates[0].method.value if candidates else None,
                "top1_confidence": round(candidates[0].confidence, 3) if candidates else None,
            }
        )

    # --- metrics -------------------------------------------------------------
    pos = [r for r in results if r["gt"] is not None]
    neg = [r for r in results if r["gt"] is None]

    top1_hits = sum(1 for r in pos if r["top1"] == r["gt"])
    top3_hits = sum(1 for r in pos if r["gt"] in r["top3"])
    auto_pos = [r for r in pos if r["status"] == "AUTO_MATCHED"]
    auto_pos_wrong = [r for r in auto_pos if r["chosen"] != r["gt"]]
    auto_neg = [r for r in neg if r["status"] == "AUTO_MATCHED"]  # false matches
    total_auto = len(auto_pos) + len(auto_neg)

    top1_acc = top1_hits / len(pos)
    top3_acc = top3_hits / len(pos)
    auto_rate = len(auto_pos) / len(pos)
    false_match_rate = (len(auto_pos_wrong) + len(auto_neg)) / total_auto if total_auto else 0.0
    correct_reject_rate = sum(1 for r in neg if r["status"] in ("NO_MATCH", "REVIEW_REQUIRED")) / len(neg)
    review_rate = sum(1 for r in pos if r["status"] == "REVIEW_REQUIRED") / len(pos)

    by_kind: dict[str, dict] = {}
    for r in pos:
        k = by_kind.setdefault(r["kind"], {"n": 0, "top1": 0, "auto": 0})
        k["n"] += 1
        k["top1"] += 1 if r["top1"] == r["gt"] else 0
        k["auto"] += 1 if r["status"] == "AUTO_MATCHED" else 0
    by_kind_out = {k: {"n": v["n"], "top1_acc": round(v["top1"] / v["n"], 4), "auto_rate": round(v["auto"] / v["n"], 4)} for k, v in by_kind.items()}

    out = {
        "metadata": {
            "engine": "rule-based-product-matcher",
            "engine_source": "app.ai.product.matching (unmodified, live from registry identity)",
            "dataset": "synthetic deterministic catalog (20 products / 5 manufacturers) + 126 queries (120 positive incl. noisy/alias/brand variants, 6 negative grocery lines)",
            "auto_accept_threshold": settings.confidence_auto_accept,
            "user_review_threshold": settings.confidence_user_review,
            "thresholds_status": _thresholds_status(),
            "date": date.today().isoformat(),
        },
        "overall": {
            "queries_positive": len(pos),
            "queries_negative": len(neg),
            "top1_accuracy": round(top1_acc, 4),
            "top3_accuracy": round(top3_acc, 4),
            "auto_match_rate": round(auto_rate, 4),
            "false_match_rate": round(false_match_rate, 4),
            "false_matches": len(auto_pos_wrong) + len(auto_neg),
            "correct_reject_rate_negatives": round(correct_reject_rate, 4),
            "review_required_rate": round(review_rate, 4),
        },
        "by_query_kind": by_kind_out,
        "per_query": results,
    }

    here = Path(__file__).parent
    (here / "PRODUCT_MATCHING_RESULTS.json").write_text(json.dumps(out, indent=2))

    md = []
    md.append("# Product Matching Evaluation (rule-based matcher)")
    md.append("")
    md.append(f"- Engine: **{out['metadata']['engine']}** (live code, identity from model registry)")
    md.append(f"- Dataset: {out['metadata']['dataset']}")
    _t = _thresholds_status().split(" (")[0]
    md.append(f"- Thresholds: auto ≥ {settings.confidence_auto_accept}, review ≥ {settings.confidence_user_review} ({_t})")
    md.append("")
    md.append("| Metric | Value |")
    md.append("| --- | --- |")
    for k, v in out["overall"].items():
        if k != "queries_positive" and k != "queries_negative":
            md.append(f"| {k} | {v} |")
    md.append("")
    md.append("By query kind (top-1 accuracy / auto rate):")
    md.append("")
    md.append("| kind | n | top1_acc | auto_rate |")
    for k, v in by_kind_out.items():
        md.append(f"| {k} | {v['n']} | {v['top1_acc']} | {v['auto_rate']} |")
    md.append("")
    md.append("Honest caveats: synthetic catalog and receipt lines (exact ground truth by construction);")
    md.append("real-world retail abbreviations, OCR noise and catalog coverage shift all numbers.")
    md.append(f"Threshold status: {_thresholds_status()}")
    (here / "PRODUCT_MATCHING_RESULTS.md").write_text("\n".join(md))

    print(json.dumps(out["overall"], indent=2))
    db.close()
    print("wrote PRODUCT_MATCHING_RESULTS.json / .md")


if __name__ == "__main__":
    main()
