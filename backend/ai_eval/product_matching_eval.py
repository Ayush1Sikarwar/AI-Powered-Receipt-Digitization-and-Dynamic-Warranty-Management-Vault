"""Product matching evaluation (TSD §41, PRD §6): Top-1 / Top-3 / false-match.

Measures the REAL matching engine (`app.ai.product.matching`) against a
deterministic synthetic catalog + query set in a dedicated eval database.
Nothing is invented: queries and ground truth are generated by this script,
the engine runs unmodified, and metrics are computed from its output.

Output: PRODUCT_MATCHING_RESULTS.json / .md next to this file.
"""

