def _thresholds_status() -> str:
    """Derive the confidence-threshold status from the measured PRD §5 floor.

    Reads `metadata.floor_met` from RESULTS.json (written by
    run_evaluation.py). Missing/unreadable artifact -> PROVISIONAL
    (conservative), mirroring app.ai.registry.thresholds_provisional().
    """
    try:
        meta = json.loads((Path(__file__).parent / "RESULTS.json").read_text())["metadata"]
    except (OSError, ValueError, KeyError):
        return "PROVISIONAL (evaluation artifact missing — see RESULTS.json metadata)"
    if meta.get("floor_met"):
        return "FINAL (PRD §5 evaluation dataset floor met — see RESULTS.json metadata)"
    return "PROVISIONAL (evaluation dataset floor not met — see RESULTS.json metadata)"

